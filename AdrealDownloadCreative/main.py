@dataclass
class RuntimeStats:
    """Агреговані метрики часу/кількості для подальшого запису в runtime JSON."""

    video_download_sec: float = 0.0
    youtube_download_sec: float = 0.0
    image_download_sec: float = 0.0
    html_download_sec: float = 0.0

    video_items: int = 0
    youtube_items: int = 0
    image_items: int = 0
    html_items: int = 0

    _lock: threading.Lock = field(default_factory=threading.Lock, repr=False)

    def add_video(self, sec: float) -> None:
        with self._lock:
            self.video_download_sec += float(sec)
            self.video_items += 1

    def add_youtube(self, sec: float, ok_count: int) -> None:
        with self._lock:
            self.youtube_download_sec += float(sec)
            self.youtube_items += int(ok_count)

    def add_image(self, sec: float) -> None:
        with self._lock:
            self.image_download_sec += float(sec)
            self.image_items += 1

    def add_html(self, sec: float) -> None:
        with self._lock:
            self.html_download_sec += float(sec)
            self.html_items += 1


