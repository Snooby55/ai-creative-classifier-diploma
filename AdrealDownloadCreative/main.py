def setup_logging():
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s | %(message)s",
        datefmt="%H:%M:%S",
    )


def run(cfg: Optional[Config] = None) -> Dict[str, Any]:
    """Запускає вигрузку креативів.

    Повертає runtime-метрики як dict, щоб зовнішній раннер міг сам вирішити,
    що і куди писати (JSON, логування, тощо).
    """
    setup_logging()
    cfg = cfg or Config()
    today = date.today()

    links = read_links(cfg.input_file, must_contain=cfg.root_host)
    if not links:
        logging.warning("Немає валідних лінків у links.txt")
        return {
            "download_time_total_wall_sec": 0.0,
            "download_time_video_direct_sec": 0.0,
            "download_time_video_youtube_sec": 0.0,
            "download_time_images_sec": 0.0,
            "download_time_html_sec": 0.0,
            "downloaded_video_direct_items": 0,
            "downloaded_video_youtube_items": 0,
            "downloaded_image_items": 0,
            "downloaded_html_items": 0,
        }

    out_dir = make_output_dir(cfg, today)
    session = build_session(cfg)

    runtime_stats = RuntimeStats()

    # воркери для скрінів
    shared_shot_queue = queue.Queue(maxsize=cfg.screenshot_queue_maxsize)
    shot_workers = [ScreenshotWorker(cfg, out_dir, shared_shot_queue, runtime_stats) for _ in range(cfg.screenshot_workers)]
    for w in shot_workers:
        w.start()

    # воркери для YouTube (Selenium -> кидає в процес-пул)
    yt_pool = YouTubeProcessPool(cfg, out_dir)
    yt_workers = [YouTubeWorker(cfg, out_dir, yt_pool) for _ in range(cfg.youtube_workers)]
    for w in yt_workers:
        w.start()

    def yt_enqueue(idx: int, parent_page_url: str, brand: str) -> None:
        # простий round-robin, щоб розкидати задачі між воркерами
        if not yt_workers:
            return
        worker = yt_workers[(idx - 1) % len(yt_workers)]
        worker.enqueue(idx, parent_page_url, brand)

    # обробка лінків у пулі потоків
    from concurrent.futures import ThreadPoolExecutor, as_completed

    t0 = time.perf_counter()
    results: List[Tuple[str, int, str, str, str]] = []

    # коректний вихід Ctrl+C
    stop_event = threading.Event()

    def _sigint(_sig, _frm):
        stop_event.set()
        logging.warning("Зупинка за сигналом. Чекаю завершення задач…")

    signal.signal(signal.SIGINT, _sigint)

    try:
        with ThreadPoolExecutor(max_workers=cfg.max_workers) as ex:
            futs = {
                ex.submit(
                    process_link,
                    i,
                    link,
                    session,
                    cfg,
                    out_dir,
                    shared_shot_queue,
                    yt_enqueue,
                    runtime_stats,
                ): i
                for i, link in enumerate(links, start=1)
            }
            total = len(futs)
            done = 0
            for fut in as_completed(futs):
                if stop_event.is_set():
                    break
                try:
                    results.append(fut.result())
                except Exception as e:
                    logging.error(f"Помилка в задачі: {e}")
                done += 1
                if done % 50 == 0 or done == total:
                    elapsed = time.perf_counter() - t0
                    logging.info(f"Прогрес: [1;32m{done}[0m/[1;32m{total}[0m ({done / total * 100:.1f}%), {elapsed:.1f}s")

    finally:
        # 1) дочекайся, поки всі скріни доробляться
        shared_shot_queue.join()
        for w in shot_workers:
            w.stop()
        for w in shot_workers:
            w.join(timeout=5)

        # 2) дочекайся, поки Selenium-ютуб-черги спорожніють
        for w in yt_workers:
            w.tasks.join()
            w.stop()
        for w in yt_workers:
            w.join(timeout=5)

        # 3) дочекайся, поки процеси yt_dlp завершаться + зберемо статистику
        yt_ok_count, yt_elapsed_sum = yt_pool.shutdown_and_collect()
        runtime_stats.add_youtube(yt_elapsed_sum, ok_count=yt_ok_count)
        # NOTE: youtube_items — це кількість ок успішних. elapsed_sum — сумарний час у процесах.

    # запис TXT з додатковою колонкою type
    with cfg.output_txt.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["link", "status", "brand", "number", "type"])
        for row in results:
            w.writerow(row)

    # runtime-метрики (повертаємо dict; писати у файл — справа раннера/CLI)
    total_elapsed = time.perf_counter() - t0
    runtime_payload: Dict[str, Any] = {
        "download_time_total_wall_sec": float(total_elapsed),
        "download_time_video_direct_sec": float(runtime_stats.video_download_sec),
        "download_time_video_youtube_sec": float(runtime_stats.youtube_download_sec),
        "download_time_images_sec": float(runtime_stats.image_download_sec),
        "download_time_html_sec": float(runtime_stats.html_download_sec),
        "downloaded_video_direct_items": int(runtime_stats.video_items),
        "downloaded_video_youtube_items": int(runtime_stats.youtube_items),
        "downloaded_image_items": int(runtime_stats.image_items),
        "downloaded_html_items": int(runtime_stats.html_items),
    }

    logging.info(f"Готово. Оброблено {len(results)} посилань за [93m{total_elapsed:.1f}s[00m")
    logging.info(f"Вихідні файли: [91m{out_dir}[00m | Лог TXT: [91m{cfg.output_txt}[00m")

    return runtime_payload


def cli() -> int:
    """CLI entrypoint"""
    cfg = Config()
    runtime_payload = run(cfg)
    try:
        cfg.runtime_json.write_text(
            json.dumps(runtime_payload, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
    except Exception as exc:
        logging.warning(f"Не вдалося записати runtime JSON {cfg.runtime_json}: {exc}")
        return 2
    return 0


if __name__ == "__main__":
    run()
