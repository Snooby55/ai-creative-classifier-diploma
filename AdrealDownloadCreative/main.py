def is_sabr_only(yt_url: str, cookiefile_path: str | None = None) -> bool:
    """Перевірка через yt_dlp.extract_info (формати лише storyboard або відсутні)."""
    try:
        import yt_dlp
    except Exception:
        return False

    opts = {
        "quiet": True,
        "no_warnings": True,
        "skip_download": True,
        "extract_flat": False,
    }
    if cookiefile_path:
        opts["cookiefile"] = cookiefile_path

    try:
        with yt_dlp.YoutubeDL(opts) as ydl:
            info = ydl.extract_info(yt_url, download=False)
        fmts = info.get("formats", [])
        if not fmts:
            return True
        has_video = any(f.get("vcodec") != "none" and f.get("url") for f in fmts)
        is_only_storyboard = all(f.get("ext") == "mhtml" for f in fmts)
        return (not has_video) or is_only_storyboard
    except Exception as e:
        logging.warning(f"SABR перевірка не вдалася ({e}) → вважаємо SABR")
        return True

def download_youtube_core_mp(
    idx: int,
    yt_url: str,
    brand: str,
    out_dir: Path,
    cfg: Config,
    cookiefile_path: Optional[str] = None,
) -> tuple[bool, float]:
    """
    Завантажує YouTube відео у окремому процесі без Selenium.

    Повертає (ok, elapsed_sec) щоб головний процес міг порахувати час по відео.
    """
    start = time.perf_counter()
    ok = False

    try:
        import yt_dlp  # type: ignore

        # 1) SABR/порожні формати: якщо там немає відео — не качаємо
        try:
            opts_probe: dict = {
                "quiet": True,
                "no_warnings": True,
                "skip_download": True,
                "extract_flat": False,
            }
            if cookiefile_path:
                opts_probe["cookiefile"] = cookiefile_path

            with yt_dlp.YoutubeDL(opts_probe) as ydl:
                info = ydl.extract_info(yt_url, download=False)

            fmts = info.get("formats", []) or []
            if not fmts or all(f.get("ext") == "mhtml" for f in fmts):
                logging.warning(f"[{idx}] SABR-only: пропускаємо завантаження.")
                return False, time.perf_counter() - start
        except Exception as exc:
            logging.warning(f"[{idx}] SABR перевірка не вдалася: {exc}")

        # 2) Параметри для завантаження
        out_path = out_dir / f"{idx}_{brand or 'NA'}_{date.today().isoformat()}.mp4"
        ydl_opts: dict = {
            "outtmpl": str(out_path),
            "quiet": False,          # можна увімкнути лог для дебагу
            "no_warnings": True,
            "noplaylist": True,
            "format": (
                f"best[ext=mp4][height<={cfg.max_video_height}]"
                f"/best[height<={cfg.max_video_height}]"
            ),
            "nopart": True,
            "updatetime": False,
            "merge_output_format": None,
            "ffmpeg_location": cfg.ffmpeg_path,
            "ignoreerrors": True,
            "concurrent_fragment_downloads": 3,
            "extractor_args": {"youtube": {"player_client": ["android", "web"]}},
        }
        if cookiefile_path:
            ydl_opts["cookiefile"] = cookiefile_path

        # 3) Основна спроба
        try:
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.download([yt_url])
            logging.info(f"[{idx}] YouTube(proc) збережено: {out_path.name}")
            ok = True
        except Exception as exc:
            logging.warning(f"[{idx}] yt_dlp primary помилка: {exc}")

        # 4) fallback
        if not ok:
            try:
                ydl_opts["format"] = "best"
                with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                    ydl.download([yt_url])
                logging.info(f"[{idx}] YouTube(proc-fallback) збережено: {out_path.name}")
                ok = True
            except Exception as exc:
                logging.error(f"[{idx}] fallback не вдалось: {exc}")

    except Exception as exc:
        logging.error(f"[{idx}] YouTube(proc) критична помилка: {exc}")

    return ok, time.perf_counter() - start


def download_youtube_core(
        drv,
        idx: int,
        parent_page_url: str,
        brand: str,
        out_dir: Path,
        cfg: Config,
        yt_pool: "YouTubeProcessPool",
) -> bool:
    import yt_dlp
    cookiefile_path = None
    try:
        drv.get(parent_page_url)
        # знайти iframe
        try:
            iframe_el = WebDriverWait(drv, cfg.page_load_timeout).until(
                EC.presence_of_element_located(
                    (By.XPATH, "//iframe[contains(@src, 'youtube.com') or contains(@src, 'youtu.be')]")
                )
            )
        except Exception:
            logging.error(f"[{idx}] Не знайдено YouTube iframe на сторінці")
            return False

        drv.switch_to.frame(iframe_el)
        yt_url = None
        try:
            link_el = WebDriverWait(drv, 3).until(
                EC.presence_of_element_located((By.CLASS_NAME, "ytp-impression-link"))
            )
            yt_url = link_el.get_attribute("href")
        except Exception:
            pass
        if not yt_url:
            drv.switch_to.default_content()
            yt_url = iframe_el.get_attribute("src")

        # куки
        cookies = drv.get_cookies()
        cookiefile_path = cookies_to_netscape_file(cookies)

        # замість прямого yt_dlp — відправляємо у пул процесів
        yt_pool.enqueue(idx, yt_url, brand, cookiefile_path)
        logging.info(f"[{idx}] YouTube завдання відправлено у процес")
        return True

    except Exception as e:
        logging.error(f"[\033[32m{idx}\033[0m] YouTube помилка: {e}")
        return False
    finally:
        if cookiefile_path:
            try:
                os.remove(cookiefile_path)
            except Exception:
                pass


class YouTubeWorker(threading.Thread):
    def __init__(self, cfg: Config, out_dir: Path, yt_pool: "YouTubeProcessPool"):
        super().__init__(daemon=True)
        self.cfg = cfg
        self.out_dir = out_dir
        self.yt_pool = yt_pool
        self.tasks: "queue.Queue[Tuple[int, str, str]]" = queue.Queue(maxsize=50)
        self._stop_event = threading.Event()
        self._drv = make_headless_driver(cfg)

    def run(self):
        while not self._stop_event.is_set():
            try:
                idx, url, brand = self.tasks.get(timeout=0.5)
            except queue.Empty:
                continue
            try:
                download_youtube_core(self._drv, idx, url, brand, self.out_dir, self.cfg, self.yt_pool)
            except Exception as e:
                logging.error(f"[\033[32m[YTW]\033[0m] #[\033[32m{idx}\033[0m] помилка: {e}")
            finally:
                self.tasks.task_done()
        try:
            self._drv.quit()
        except Exception:
            pass

    def enqueue(self, idx: int, url: str, brand: str):
        self.tasks.put((idx, url, brand))

    def stop(self):
        self._stop_event.set()

class YouTubeProcessPool:
    def __init__(self, cfg: Config, out_dir: Path):
        self.cfg = cfg
        self.out_dir = out_dir
        self.executor = ProcessPoolExecutor(max_workers=cfg.youtube_workers)
        self._futures = []
        self._lock = threading.Lock()

    def enqueue(
        self,
        idx: int,
        yt_url: str,
        brand: str,
        cookiefile_path: str | None = None,
    ) -> None:
        """Передає завдання у окремий процес (асинхронно)."""
        fut = self.executor.submit(
            download_youtube_core_mp,
            idx,
            yt_url,
            brand,
            self.out_dir,
            self.cfg,
            cookiefile_path,
        )
        with self._lock:
            self._futures.append(fut)

    def shutdown_and_collect(self) -> tuple[int, float]:
        """
        Коректне завершення + збір статистики.
        Повертає (ok_count, total_elapsed_sec) по YouTube-відео.
        """
        self.executor.shutdown(wait=True)

        ok_count = 0
        elapsed_sum = 0.0

        with self._lock:
            futures = list(self._futures)

        for fut in futures:
            try:
                ok, elapsed = fut.result()
                if ok:
                    ok_count += 1
                elapsed_sum += float(elapsed)
            except Exception:
                # якщо процес упав/викинув виключення — просто не рахуємо ok,
                # але врахувати час неможливо
                continue

        return ok_count, elapsed_sum


