def process_link(
    idx: int,
    url: str,
    session: requests.Session,
    cfg: Config,
    out_dir: Path,
    shot_queue: "queue.Queue[Tuple[int, str, str]]",
    yt_enqueue,
    runtime_stats: RuntimeStats,
) -> Tuple[str, int, str, str, str]:
    """
    Повертає: (link, http_status, brand, number_or_empty, media_type)

    number_or_empty = str(idx) якщо щось збережено (медіа або скрін), інакше "".
    media_type: "video" | "html" | "banner" | ""
    """
    t0 = time.perf_counter()
    brand = ""
    saved_any = False
    media_type = ""

    try:
        resp = session.get(url, timeout=cfg.request_timeout)
    except requests.RequestException as e:
        logging.error(f"[{idx}] GET failed: {e}")
        return url, 0, brand, "", ""

    status = resp.status_code
    if status != 200 or not resp.text:
        return url, status, brand, "", ""

    brand = parse_brand(resp.text) or ""

    imgs, videos, iframes, iframes_youtube = find_media_blocks(resp.text)

    if cfg.media_first_strategy:
        media_type = try_save_media(
            idx=idx,
            page_url=url,
            brand=brand,
            img_urls=imgs,
            video_urls=videos,
            iframe_urls=iframes,
            iframes_youtube_urls=iframes_youtube,
            session=session,
            cfg=cfg,
            out_dir=out_dir,
            yt_enqueue=yt_enqueue,
            runtime_stats=runtime_stats,
        )

        # Якщо HTML-вигрузка вимкнена в config.py і сторінка може дати лише .html —
        # вважаємо, що "нічого не вивантажили" (без змін у самій логіці save_*).
        if media_type == dlcfg.HTML_DISABLED_RESULT:
            logging.info(f"[{idx}] HTML disabled → mark as not downloaded")
            return url, status, "", "", ""

        saved_any = bool(media_type)

    if not saved_any:
        if dlcfg.ALLOW_SCREENSHOT_FALLBACK:
            out_name = f"{idx}_{brand or 'NA'}_{date.today().isoformat()}.png"
            shot_queue.put((idx, url, out_name))
            saved_any = True
            media_type = "banner"  # скрін банеру
        else:
            # Нічого не зберігаємо (корисно для дебагу або якщо хочете лише відео тощо)
            saved_any = False
            media_type = ""

    dt = time.perf_counter() - t0
    logging.info(
        f"[[32m{idx}[0m] done in {dt:.2f}s (saved={saved_any}, type={media_type})"
    )
    return url, status, brand, str(idx) if saved_any else "", media_type


def try_save_media(
    *,
    idx: int,
    page_url: str,
    brand: str,
    img_urls: Iterable[str],
    video_urls: Iterable[str],
    iframe_urls: Iterable[str],
    iframes_youtube_urls: Iterable[str],
    session: requests.Session,
    cfg: Config,
    out_dir: Path,
    yt_enqueue,
    runtime_stats: RuntimeStats,
) -> str:
    today = date.today().isoformat()

    # ---- зображення (якщо колись знову увімкнете) ----
    # for src in img_urls:
    #     abs_url = absolute_url(page_url, src, cfg)
    #     st0 = time.perf_counter()
    #     try:
    #         r = session.get(abs_url, timeout=cfg.request_timeout)
    #         if r.status_code != 200:
    #             continue
    #         ext = guess_ext_from_headers_or_url(r, abs_url, default=".jpg")
    #         try:
    #             with Image.open(BytesIO(r.content)) as im:
    #                 if im.width < 36 and im.height < 36:
    #                     continue
    #         except Exception:
    #             continue
    #         out = out_dir / f"{idx}_{brand or 'NA'}_{today}{ext}"
    #         save_image_safely(r.content, out)
    #         runtime_stats.add_image(time.perf_counter() - st0)
    #         return "image"
    #     except requests.RequestException:
    #         continue

    # ---- відео (пряме) ----
    for src in video_urls:
        abs_url = absolute_url(page_url, src, cfg)
        st0 = time.perf_counter()
        try:
            r = session.get(abs_url, timeout=cfg.request_timeout, stream=True)
            if r.status_code != 200:
                continue
            out = out_dir / f"{idx}_{brand or 'NA'}_{today}.mp4"
            save_stream(out, r, cfg.max_video_height * cfg.max_video_height)
            runtime_stats.add_video(time.perf_counter() - st0)
            return "video"
        except requests.RequestException:
            continue

    # ---- iframe ----
    for src in iframe_urls:
        abs_url = absolute_url(page_url, src, cfg)

        # 1) пробуємо витягти відео з контенту iframe
        inner_videos = extract_videos_from_iframe(abs_url, session, cfg)
        for v in inner_videos:
            st0 = time.perf_counter()
            try:
                r = session.get(v, timeout=cfg.request_timeout, stream=True)
                if r.status_code != 200:
                    continue
                out = out_dir / f"{idx}_{brand or 'NA'}_{today}.mp4"
                save_stream(out, r, cfg.max_video_height * cfg.max_video_height)
                runtime_stats.add_video(time.perf_counter() - st0)
                return "video"
            except requests.RequestException:
                continue

        # 2) якщо відео не знайшли — опційно збережемо HTML як є
        st0 = time.perf_counter()
        try:
            r = session.get(abs_url, timeout=cfg.request_timeout)
            if r.status_code != 200 or not r.content:
                continue

            # HTML може бути вимкнений (щоб не плодити .html файли)
            if not dlcfg.ALLOW_HTML_DOWNLOAD:
                # 1) "mark_failed" — повертаємо спец-токен, щоб process_link записав
                #    як "нічого не вивантажили" (порожні number/type)
                if dlcfg.HTML_DISABLED_BEHAVIOR == "mark_failed":
                    return dlcfg.HTML_DISABLED_RESULT
                # 2) "screenshot" — просто ігноруємо цей iframe і дамо впасти у скрін
                continue

            out = out_dir / f"{idx}_{brand or 'NA'}_{today}.html"
            save_bytes(out, r.content)
            runtime_stats.add_html(time.perf_counter() - st0)
            return "html"
        except requests.RequestException:
            continue

    # ---- YouTube iframe ----
    if iframes_youtube_urls:
        # тут нам треба Selenium, щоб витягнути справжній yt_url і куки.
        # Робимо це через YouTubeWorker, який потім кидає задачу в процес-пул.
        yt_enqueue(idx, page_url, brand)
        return "video"

    return ""


def guess_ext_from_headers_or_url(resp: requests.Response, url: str, default: str = ".bin") -> str:
    ctype = resp.headers.get("Content-Type", "")
    if "image/png" in ctype:
        return ".png"
    if "image/jpeg" in ctype:
        return ".jpg"
    if "image/gif" in ctype:
        return ".gif"
    if "video/mp4" in ctype:
        return ".mp4"

    # з URL
    path = urlparse(url).path.lower()
    for ext in (".png", ".jpg", ".jpeg", ".gif", ".mp4", ".webm"):
        if path.endswith(ext):
            return ".jpg" if ext == ".jpeg" else ext
    return default


