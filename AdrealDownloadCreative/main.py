class ScreenshotWorker(threading.Thread):
    def __init__(self, cfg: Config, out_dir: Path, tasks_queue: "queue.Queue[Tuple[int,str,str]]", runtime_stats: RuntimeStats):
        super().__init__(daemon=True)
        self.cfg = cfg
        self.out_dir = out_dir
        self.tasks = tasks_queue   # <- тепер використовуємо зовнішню чергу
        self.runtime_stats = runtime_stats
        self._stop_event = threading.Event()
        self._driver = None


    def run(self):
        self._driver = self._make_driver()
        try:
            while not self._stop_event.is_set():  # <- виправлено
                try:
                    number, url, out_name = self.tasks.get(timeout=0.25)
                except queue.Empty:
                    continue
                try:
                    st0 = time.perf_counter()
                    self._take_screenshot(url, self.out_dir / out_name)
                    self.runtime_stats.add_image(time.perf_counter() - st0)
                except Exception as e:
                    logging.error(f"[screenshot] #{number} failed: {e}")
                finally:
                    self.tasks.task_done()
        finally:
            if self._driver:
                try:
                    self._driver.quit()
                except Exception:
                    pass

    def stop(self):
        self._stop_event.set()  # <- виправлено

    def enqueue(self, number: int, url: str, out_name: str):
        self.tasks.put((number, url, out_name))

    def join_until_empty(self):
        self.tasks.join()

    def _make_driver(self):
        # Chrome за замовчуванням; якщо немає — пробуємо Edge.
        opts = webdriver.ChromeOptions()
        if self.cfg.headless:
            opts.add_argument("--headless=new")
            opts.add_argument("--disable-gpu")
            opts.add_argument("--log-level=3")
        opts.add_argument(f"--window-size={self.cfg.window_size}")
        opts.add_experimental_option("excludeSwitches", ["enable-logging"])
        opts.add_argument(f"user-agent={self.cfg.user_agent}")

        try:
            driver = webdriver.Chrome(options=opts)
        except Exception:
            # fallback: Edge
            eopts = webdriver.EdgeOptions()
            if self.cfg.headless:
                eopts.add_argument("--headless=new")
                eopts.add_argument("--disable-gpu")
                eopts.add_argument("--log-level=3")
            eopts.add_argument(f"--window-size={self.cfg.window_size}")
            eopts.add_experimental_option("excludeSwitches", ["enable-logging"])
            eopts.add_argument(f"user-agent={self.cfg.user_agent}")
            driver = webdriver.Edge(options=eopts)

        driver.set_page_load_timeout(self.cfg.page_load_timeout)
        return driver

    def _take_screenshot(self, url: str, out_path: Path):
        drv = self._driver
        drv.get(url)
        WebDriverWait(drv, self.cfg.page_load_timeout).until(
            EC.visibility_of_element_located(self.cfg.page_ready_selector)
        )

        # Масштабування вікна так, щоб елемент помістився
        drv.execute_script("""
            const el = document.evaluate(arguments[0], document, null, XPathResult.FIRST_ORDERED_NODE_TYPE, null).singleNodeValue;
            if (!el) return;
            document.body.style.zoom = 1;

            const elementWidth = el.clientWidth;
            const elementHeight = el.clientHeight;
            const windowWidth = window.innerWidth;
            const windowHeight = window.innerHeight;

            const widthRatio = windowWidth / Math.max(1, elementWidth);
            const heightRatio = windowHeight / Math.max(1, elementHeight);
            const zoomFactor = Math.min(widthRatio, heightRatio, 1);

            document.body.style.zoom = zoomFactor;

            const rect = el.getBoundingClientRect();
            const scrollLeft = window.pageXOffset + rect.left * zoomFactor - (windowWidth - rect.width * zoomFactor) / 2;
            const scrollTop  = window.pageYOffset + rect.top * zoomFactor  - (windowHeight - rect.height * zoomFactor) / 2;

            const extra = elementHeight * 0.2 * zoomFactor;
            window.scrollTo({ top: scrollTop + extra, left: scrollLeft, behavior: 'instant' });
        """, self.cfg.element_screenshot_xpath)

        # якщо елемент знайдеться — робимо скрін елемента; інакше — фулпейдж
        try:
            el = drv.find_element(By.XPATH, self.cfg.element_screenshot_xpath)
            el.screenshot(str(out_path))
        except Exception:
            drv.save_screenshot(str(out_path))


