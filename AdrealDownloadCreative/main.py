def cookies_to_netscape_file(cookies: List[dict]) -> str:
    """
    Приймає cookies з Selenium (driver.get_cookies()) і повертає ШЛЯХ до тимчасового
    Netscape cookie файлу. Файл треба видаляти вручну після використання.
    """
    now = int(time.time())
    tf = tempfile.NamedTemporaryFile("w", suffix=".cookies.txt", delete=False, encoding="utf-8")
    try:
        tf.write("# Netscape HTTP Cookie File\n")
        tf.write("# This file was generated by Selenium\n\n")
        for c in cookies:
            domain = c.get("domain", "")
            flag = "TRUE" if domain.startswith(".") else "FALSE"
            path = c.get("path", "/")
            secure = "TRUE" if c.get("secure", False) else "FALSE"
            expiry = int(c.get("expiry", now + 3600))
            name = c.get("name", "")
            value = c.get("value", "")
            tf.write(f"{domain}\t{flag}\t{path}\t{secure}\t{expiry}\t{name}\t{value}\n")
        tf.flush()
        return tf.name
    finally:
        tf.close()


