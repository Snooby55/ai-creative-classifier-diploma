def save_stream(path: Path, resp: requests.Response, chunk: int = 1024 * 1024) -> None:
    with path.open("wb") as f:
        for part in resp.iter_content(chunk_size=chunk):
            if part:
                f.write(part)


def save_image_safely(img_bytes: bytes, path: Path) -> None:
    try:
        with Image.open(BytesIO(img_bytes)) as im:
            try:
                im.save(path)
            except Exception:
                try:
                    im.convert("RGBA").save(path)
                except Exception:
                    im.convert("RGB").save(path)
    except Exception as e:
        raise RuntimeError(f"Bad image data: {e}")


def parse_brand(html: str) -> Optional[str]:
    # Приклад: шукаємо "Brand:" далі <a href="#">Name</a>
    soup = BeautifulSoup(html, "html.parser")
    # гнучкіше: знайдемо текст "Brand:" і сусіднє <a>
    brand_text = soup.find(string=lambda s: isinstance(s, str) and "Brand:" in s)
    if not brand_text:
        return None
    # частіше це в околі
    anchor = soup.select_one('a[href="#"]')
    if anchor and anchor.text.strip():
        return sanitize_name(anchor.text.strip())
    # fallback — грубим регексом
    m = re.search(r'Brand:.*?<a[^>]*>([^<]+)</a>', html, re.IGNORECASE | re.DOTALL)
    if m:
        return sanitize_name(m.group(1).strip())
    return None


def find_media_blocks(html: str) -> Tuple[List[str], List[str], List[str]]:
    """
    Повертає кортеж списків: (img_urls, video_urls, iframe_urls)
    Підтримує як відносні шляхи /files/... так і повні зовнішні.
    """
    soup = BeautifulSoup(html, "html.parser")
    main = soup.find(id="mainRow") or soup  # якщо нема, парсимо все

    img_urls = []
    for tag in main.find_all("img"):
        src = tag.get("src")
        if not src:
            continue
        img_urls.append(src)

    video_urls = []
    for tag in main.find_all("video"):
        src = tag.get("src")
        if not src:
            continue
        video_urls.append(src)

    video_urls = []
    for v in main.find_all("video"):
        # 1) <video src="...">
        if v.get("src"):
            video_urls.append(v.get("src"))
        # 2) <video><source src="..."></video>
        for s in v.find_all("source"):
            if s.get("src"):
                video_urls.append(s.get("src"))

    iframe_urls = []
    iframe_youtube_urls = []
    for tag in main.find_all("iframe"):
        src = tag.get("src")
        if not src:
            continue
        if "youtube.com" in src or "youtu.be" in src:
            iframe_youtube_urls.append(src)
            continue
        iframe_urls.append(src)

    return img_urls, video_urls, iframe_urls, iframe_youtube_urls


def absolute_url(base: str, url: str, cfg: Config) -> str:
    # Якщо зовнішній домен — віддаємо як є; якщо відносний — приєднуємо до root_host.
    if url.startswith(("http://", "https://")):
        return url
    return urljoin(base or cfg.root_host, url)


